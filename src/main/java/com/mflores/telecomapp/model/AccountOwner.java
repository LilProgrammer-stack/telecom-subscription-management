package com.mflores.telecomapp.model;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.Generated;

import java.time.LocalDate;
import java.time.OffsetDateTime;

@Data
@NoArgsConstructor
@AllArgsConstructor
@Entity
@Table(name = "account_owner")
public class AccountOwner {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "account_owner_id", nullable = false)
    private Long accountOwnerId;
    @Column(name = "first_name", nullable = false)
    private String firstName;
    @Column(name = "last_name", nullable = false)
    private String lastName;
    @Column(name = "date_of_birth", nullable = false)
    private LocalDate dateOfBirth;
    //We're letting Jpa/Hibernate know this cannot be updatable even if we try to
    @Generated //value is generated by the database
    @Column(name = "created_at", nullable = false, updatable = false)
    private OffsetDateTime createdAt;
    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_account_id", nullable = false, unique = true)
    private UserAccount userAccount;

    public AccountOwner(String firstName, String lastName, UserAccount userAccount, LocalDate dateOfBirth) {
        this.firstName = firstName;
        this.lastName = lastName;
        this.userAccount = userAccount;
        this.dateOfBirth = dateOfBirth;
    }

    public AccountOwner(String firstName, String lastName, UserAccount userAccount, LocalDate dateOfBirth, OffsetDateTime createdAt) {
        this.firstName = firstName;
        this.lastName = lastName;
        this.userAccount = userAccount;
        this.dateOfBirth = dateOfBirth;
        this.createdAt = createdAt;
    }
}
