CREATE TABLE email_update_token
(

    email_update_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hashed_token          VARCHAR(255)             NOT NULL UNIQUE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    email_update_status   VARCHAR(50)              NOT NULL,
    new_email             VARCHAR(255)             NOT NULL,
    user_account_id       BIGINT                   NOT NULL,

    CONSTRAINT fk_email_update_token_user_account
        foreign key (user_account_id)
            references user_account (user_account_id)
    );

CREATE INDEX idx_email_update_token_user_account
    ON email_update_token (user_account_id);