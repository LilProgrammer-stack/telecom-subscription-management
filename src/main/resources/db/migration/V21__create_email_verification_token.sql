CREATE TABLE email_verification_token
(
    verification_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token                 VARCHAR(255) NOT NULL UNIQUE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    used                  BOOLEAN NOT NULL,
    customer_credential_id BIGINT NOT NULL UNIQUE,

    CONSTRAINT fk_email_verification_token_customer_credential
        FOREIGN KEY (customer_credential_id)
            REFERENCES customer_credential (credential_id)
);