CREATE TABLE device_payment_agreement
(
    device_payment_agreement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date                  DATE       NOT NULL,
    end_date                    DATE,
    financed_amount             BIGINT     NOT NULL,
    financed_currency           VARCHAR(3) NOT NULL,
    total_installments          INTEGER    NOT NULL,
    paid_installments           INTEGER    NOT NULL
);

CREATE TABLE device
(
    device_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model                       VARCHAR(255) NOT NULL,
    brand                       VARCHAR(255) NOT NULL,
    imei                        VARCHAR(255) NOT NULL UNIQUE,
    locked                      BOOLEAN      NOT NULL,
    price_amount                BIGINT       NOT NULL,
    price_currency              VARCHAR(3)   NOT NULL,
    device_payment_agreement_id BIGINT UNIQUE,
    CONSTRAINT fk_device_payment_agreement
        FOREIGN KEY (device_payment_agreement_id)
            REFERENCES device_payment_agreement (device_payment_agreement_id)
);

CREATE TABLE device_assignment
(
    device_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date           DATE   NOT NULL,
    end_date             DATE,
    device_id            BIGINT NOT NULL,
    phone_line_id        BIGINT NOT NULL,
    CONSTRAINT fk_device_assignment_device
        FOREIGN KEY (device_id)
            REFERENCES device (device_id),
    CONSTRAINT fk_device_assignment_phone_line
        FOREIGN KEY (phone_line_id)
            REFERENCES phone_line (phone_line_id)
);